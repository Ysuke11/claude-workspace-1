def build_kickoff_message(business: dict, focus: str | None = None) -> str:
    """最初のユーザーメッセージを組み立てる。"""
    lines = [
        f"対象: {business.get('type', '動物病院')}"
        + (f"（{business['name']}）" if business.get("name") else ""),
        f"ゴール: {business.get('goal', '初診（新規来院）件数の増加')}",
    ]
    if business.get("trade_area_km"):
        lines.append(f"想定商圏: 半径 約{business['trade_area_km']}km")

    notes = [n for n in (business.get("notes") or []) if n]
    if notes:
        lines.append("前提:")
        lines.extend(f"  - {n}" for n in notes)

    if focus:
        lines.append(f"\n特に知りたいこと: {focus}")

    lines.append(
        "\nBigQuery のスキーマは未確認です。list_tables から始めて、"
        "初診を増やすための分析を進めてください。"
    )
    return "\n".join(lines)
